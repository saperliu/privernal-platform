package com.privernal.dynamic.dba.dialect;

import com.privernal.dynamic.dba.type.PostgreSQLTypeMapper;
import com.privernal.dynamic.dba.vo.CreateTableVo;
import com.privernal.dynamic.dba.vo.MysqlTableInfo;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Component;

/**
 * PostgreSQL 数据库方言实现
 * <p>
 * 基于 PostgreSQL 10+ 语法特性实现 SQL 构建，包含：
 * <ul>
 *   <li>{@code GENERATED BY DEFAULT AS IDENTITY} 自增列语法</li>
 *   <li>{@code ALTER COLUMN} 修改列语法</li>
 *   <li>{@code COMMENT ON COLUMN} 列注释语法</li>
 *   <li>基于 {@code pg_indexes} 的索引元数据查询</li>
 *   <li>{@code LIMIT ... OFFSET} 分页语法</li>
 * </ul>
 * </p>
 *
 * @author saperliu
 * @version 1.0.0
 */
@Component
public class PostgreSQLDialect extends AbstractDatabaseDialect {

    /** 方言名称 */
    public static final String DIALECT_NAME = "postgresql";

    /**
     * 构造函数，注入 PostgreSQL 类型映射器
     *
     * @param typeMapper PostgreSQL 类型映射器
     */
    @Autowired
    public PostgreSQLDialect(PostgreSQLTypeMapper typeMapper) {
        super(typeMapper);
        log.debug("PostgreSQLDialect initialized");
    }

    /**
     * SPI 无参构造函数（ServiceLoader 发现方言时使用，自建无状态类型映射器）
     */
    public PostgreSQLDialect() {
        super(new PostgreSQLTypeMapper());
        log.debug("PostgreSQLDialect initialized via SPI");
    }

    @Override
    public String getName() {
        return DIALECT_NAME;
    }

    @Override
    protected String buildAutoIncrementClause() {
        return "GENERATED BY DEFAULT AS IDENTITY";
    }

        /**
     * DDL 字面量转义（S16）：建表语句不支持绑定参数，COMMENT/DEFAULT 里的引号与反斜杠
     * 必须转义，否则模板作者输入即二阶 DDL 注入。
     */
    private static String escapeDdlLiteral(String value) {
        return (value == null ? "" : value).replace("\\", "\\\\").replace("'", "''");
    }

    @Override
    protected String buildDefaultValueClause(CreateTableVo vo) {
        String defaultValue = vo.getFieldDefaultValue();
        String fieldType = vo.getFieldType();

        if ("boolean".equals(fieldType)) {
            return "DEFAULT " + ("true".equals(defaultValue) ? "true" : "false");
        }

        if ("integer".equals(fieldType) || "bigint".equals(fieldType)
                || "decimal".equals(fieldType) || "double precision".equals(fieldType)) {
            // 数值型默认值不允许引号/表达式等任何杂质（DDL 无绑定参数，字面量即最终 SQL 的一部分）
            if (defaultValue == null || !defaultValue.matches("-?\\d+(\\.\\d+)?")) {
                throw new IllegalArgumentException("数值型字段的默认值必须是数字：" + defaultValue);
            }
            return "DEFAULT " + defaultValue;
        }

        if ("timestamp".equals(fieldType)) {
            return "DEFAULT '" + escapeDdlLiteral(defaultValue) + "'";
        }

        return "DEFAULT '" + escapeDdlLiteral(defaultValue) + "'";
    }

    @Override
    protected String buildCommentClause(String comment) {
        return "";
    }

    @Override
    public String buildColumnComment(String tableName, String columnName, String comment) {
        if (comment == null || comment.isEmpty()) {
            return null;
        }
        log.debug("Building column comment for {}.{}: {}", tableName, columnName, comment);
        if (!tableName.matches("[A-Za-z_][A-Za-z0-9_]*") || !columnName.matches("[A-Za-z_][A-Za-z0-9_]*")) {
            throw new IllegalArgumentException("非法的注释目标标识符：" + tableName + "." + columnName);
        }
        return "COMMENT ON COLUMN " + tableName + "." + columnName + " IS '" + escapeDdlLiteral(comment) + "'";
    }

    @Override
    protected String buildTableOptions() {
        return "";
    }

    @Override
    protected String getModifyKeyword() {
        return "ALTER COLUMN";
    }

    @Override
    public String buildAlterTableModifyColumn(String tableName, CreateTableVo column, String oldName) {
        StringBuilder sb = new StringBuilder();
        sb.append("ALTER TABLE ").append(tableName);
        sb.append(" ALTER COLUMN ").append(oldName);
        sb.append(" TYPE ").append(buildTypeDefinition(column));

        if (!column.isFieldIsNull()) {
            sb.append(", ALTER COLUMN ").append(oldName).append(" SET NOT NULL");
        }

        if (column.getFieldDefaultValue() != null && !column.getFieldDefaultValue().isEmpty()) {
            sb.append(", ALTER COLUMN ").append(oldName)
                    .append(" SET DEFAULT ").append(buildDefaultValueClause(column).replaceFirst("DEFAULT ", ""));
        }

        if (column.isFieldIsKey()) {
            sb.append(", ADD PRIMARY KEY (").append(column.getFieldName()).append(")");
        }

        log.debug("Building ALTER TABLE modify column SQL: {}", sb);
        return sb.toString();
    }

    @Override
    public String buildAlterTableRenameColumn(String tableName, String oldName, String newName) {
        return "ALTER TABLE " + tableName + " RENAME COLUMN " + oldName + " TO " + newName;
    }

    @Override
    public String buildTableExistsSql(String tableName) {
        return "SELECT COUNT(1) FROM information_schema.tables WHERE table_name = '" + tableName + "'";
    }

    @Override
    public String buildGetTableColumnsSql(String tableName) {
        return "SELECT * FROM information_schema.columns WHERE table_name = '" + tableName + "'";
    }

    @Override
    public String buildGetTableIndexesSql(String tableName) {
        return "SELECT indexname FROM pg_indexes WHERE tablename = '" + tableName
                + "' AND indexname NOT LIKE '%_pkey'";
    }

    @Override
    public String buildDropIndexSql(String tableName, String indexName) {
        return "DROP INDEX IF EXISTS " + indexName;
    }

    @Override
    public String buildPaginationSql(String baseSql, int offset, int pageSize) {
        return baseSql + " LIMIT " + pageSize + " OFFSET " + offset;
    }

    @Override
    public boolean isAutoIncrement(MysqlTableInfo info) {
        String extra = info.getExtra();
        if (extra != null && (extra.contains("auto_increment") || extra.contains("identity"))) {
            return true;
        }
        String columnDefault = info.getColumn_default();
        return columnDefault != null && columnDefault.contains("nextval");
    }

    @Override
    public boolean isPrimaryKey(MysqlTableInfo info) {
        String key = info.getColumn_key();
        return "PRI".equalsIgnoreCase(key) || info.getColumn_comment() != null
                && info.getColumn_comment().contains("pkey");
    }

    @Override
    public int parseColumnLength(MysqlTableInfo info) {
        String charLength = info.getCharacter_maximum_length();
        if (charLength != null && !charLength.isEmpty()) {
            return Integer.parseInt(charLength);
        }
        String numericPrecision = info.getNumeric_precision();
        if (numericPrecision != null && !numericPrecision.isEmpty()) {
            return Integer.parseInt(numericPrecision);
        }
        return 0;
    }

    @Override
    public String parseColumnDefaultValue(MysqlTableInfo info) {
        String defaultValue = info.getColumn_default();
        if (defaultValue == null) {
            return null;
        }
        if (defaultValue.startsWith("'") && defaultValue.endsWith("'")) {
            return defaultValue.substring(1, defaultValue.length() - 1);
        }
        return defaultValue;
    }

    /** 报表时间分组：to_char 按粒度格式化，周粒度用 ISO 周编号 */
    @Override
    public String buildTimeGroupSql(String column, String granularity) {
        String pattern;
        switch (granularity == null ? "DAY" : granularity.trim().toUpperCase()) {
            case "WEEK":
                pattern = "IYYY-IW";
                break;
            case "MONTH":
                pattern = "YYYY-MM";
                break;
            case "YEAR":
                pattern = "YYYY";
                break;
            case "HOUR":
                pattern = "YYYY-MM-DD HH24";
                break;
            case "MINUTE":
                pattern = "YYYY-MM-DD HH24:MI";
                break;
            case "DAY":
                pattern = "YYYY-MM-DD";
                break;
            default:
                throw new IllegalArgumentException("不支持的时间粒度：" + granularity);
        }
        return "to_char(" + column + ", '" + pattern + "')";
    }

    /**
     * PostgreSQL 没有 MySQL 的 MAX_EXECUTION_TIME 优化器提示，语句超时是会话级 GUC
     * （statement_timeout），不能随单条 SQL 携带。这里明确返回空串而不是沿用 MySQL 的写法：
     * 沿用只会让 SQL 里多一段被 PG 当普通注释忽略的提示，看着像限了时间其实没限。
     */
    @Override
    public String buildTimeoutHint(int timeoutMillis) {
        return "";
    }
}